/**
 * droneRun.gen.test.ts - the GENERATOR of DRONE RUN's DEV fixture, not a
 * test. Skipped unless asked for.
 *
 * Takes the BUILT-IN FIELD (level/placeholderField.ts: the level and every
 * piece's payload, authored in code), builds its world as a real publish
 * would (level/build.ts: one kind 33331 object per piece placed by reference,
 * then the world bag sealed to the region key, the entry marker inline and
 * first), signs every event with the DEV key, and writes
 * fixture/droneRun.fixture.json with the level beside the events (the app
 * reads the built-in field's zones, entry, spawns and patrol from there). The
 * DEV key's secret is read from the file DRONE_RUN_KEY names (64 hex or an
 * nsec), never printed, and nothing is sent anywhere: lib/relay is the
 * offline relay in every test file, and nothing here asks it. The fixture is
 * for LOCAL play only and is never on any relay.
 *
 *   GEN_DRONE_RUN=1 \
 *   DRONE_RUN_KEY=/data/claude/secrets/onosendai-drone-run-DEV.hex \
 *   /data/bin/heavy npx vitest run src/lib/games/droneRun/__tests__/droneRun.gen.test.ts
 *
 * Only the built-in field is ever signed into the fixture. A level imported
 * on a device (level/package.ts) is never built into events.
 * __tests__/fixture.test.ts checks the fixture and the field are one pair.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { describe, expect, it } from 'vitest'
import { getPublicKey, verifyEvent } from 'nostr-tools/pure'
import { finalizeEvent } from 'nostr-tools/pure'
import { nip19 } from 'nostr-tools'
import { hexToBytes, type EventTemplate, type NostrEvent } from '../../../events'
import { DRONE_RUN_DEV_PUBKEY, DRONE_RUN_GAME } from '../game'
import { buildDroneRunWorld } from '../level/build'
import { placeholderField } from '../level/placeholderField'

const asked = process.env.GEN_DRONE_RUN === '1'

/** A secret key from a file: 64 hex, or an nsec. */
function secretFrom(path: string): Uint8Array {
  const raw = readFileSync(path, 'utf8').trim()
  if (raw.startsWith('nsec1')) {
    const d = nip19.decode(raw)
    if (d.type !== 'nsec') throw new Error('not an nsec')
    return d.data
  }
  return hexToBytes(raw)
}

describe('DRONE RUN (generator)', () => {
  it.skipIf(!asked)('signs the DEV world and writes the fixture', async () => {
    const sk = secretFrom(process.env.DRONE_RUN_KEY ?? '')
    if (getPublicKey(sk) !== DRONE_RUN_DEV_PUBKEY) throw new Error('The DEV fixture is only ever signed by the DEV key.')
    const { level, payloads } = placeholderField()
    const sign = (t: EventTemplate): NostrEvent => JSON.parse(JSON.stringify(finalizeEvent({ kind: t.kind, created_at: t.created_at, tags: t.tags, content: t.content }, sk))) as NostrEvent
    // One fixed moment, so a regenerated fixture differs only in its nonces and signatures.
    const built = await buildDroneRunWorld(DRONE_RUN_GAME, sign, level, payloads, 1_794_800_000)
    for (const e of built.events) expect(verifyEvent(e)).toBe(true)
    const out = resolve(__dirname, '..', 'fixture', 'droneRun.fixture.json')
    const about = 'DRONE RUN\'s built-in field, signed by a DEV key: the level it was built from, then one kind 33331 object per piece placed by reference and the world bag sealed to the region key. For LOCAL play only; never on any relay. Generated by src/lib/games/droneRun/__tests__/droneRun.gen.test.ts from level/placeholderField.ts.'
    const text = JSON.stringify({ about, level, events: built.events }) + '\n'
    writeFileSync(out, text)
    console.log(`wrote ${out}: ${built.events.length} events (${built.referenced.length} objects, then the bag), ${built.inline.length} pieces inline, bag ${built.bagBytes} bytes, file ${Buffer.byteLength(text)} bytes`)
  })

  it('builds for the DEV game', () => {
    expect(DRONE_RUN_GAME.pubkey).toBe(DRONE_RUN_DEV_PUBKEY)
  })
})
